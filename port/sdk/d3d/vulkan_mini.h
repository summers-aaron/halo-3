/*
 * The subset of the Vulkan 1.3 API the PC port's Vulkan backend uses (port/sdk/d3d/vulkan_backend.cpp), with
 * VK_KHR_surface, VK_KHR_swapchain, VK_KHR_win32_surface, VK_KHR_xlib_surface, VK_KHR_xcb_surface,
 * VK_EXT_headless_surface and VK_EXT_debug_utils. Self-contained: the Windows build is cross-compiled with no Vulkan
 * SDK (and no C library headers), so nothing here includes a Vulkan header. The loader is opened at run time
 * (port/sdk/d3d/vulkan_host.h), so no prototypes are declared, only the PFN_ types and s_vulkan_functions.
 *
 * Source: the Khronos Vulkan headers (vulkan_core.h, vulkan_win32.h, vulkan_xlib.h, vulkan_xcb.h; header version
 * 341; Apache-2.0 OR MIT): struct definitions, enumerant values and PFN signatures are copied from them verbatim,
 * and every struct size, member offset, enumerant value and PFN parameter list was checked against those headers
 * when compiled for i686-linux-gnu and for i686-pc-windows-msvc.
 *
 * ABI: as in vk_platform.h, Vulkan entry points are __stdcall on Windows (vulkan-1.dll) and plain cdecl on Linux
 * (libvulkan.so.1). On 32-bit targets non-dispatchable handles are uint64_t. uint64_t members (handles,
 * VkDeviceSize) are laid out by the target's own C ABI, exactly as the Khronos headers leave them: 8-byte aligned in
 * structs on i686-pc-windows-msvc, 4-byte aligned on i686-linux-gnu (where libvulkan and the drivers are built with
 * the same ABI). Consequently a Vulkan struct must never cross between the game's MS-ABI code (on Linux:
 * i686-pc-windows-msvc-elf) and host code: only the host-ABI backend fills in and passes these structs.
 */

