#define SEVERITY_SUCCESS 0
#define SEVERITY_ERROR 1

#define SUCCEEDED(Status) ((HRESULT)(Status) >= 0)
#define FAILED(Status) ((HRESULT)(Status) < 0)
#define IS_ERROR(Status) ((unsigned long)(Status) >> 31 == SEVERITY_ERROR)
#define HRESULT_CODE(hr) ((hr) & 0xFFFF)
#define SCODE_CODE(sc) ((sc) & 0xFFFF)
#define HRESULT_FACILITY(hr) (((hr) >> 16) & 0x1fff)
#define SCODE_FACILITY(sc) (((sc) >> 16) & 0x1fff)
#define HRESULT_SEVERITY(hr) (((hr) >> 31) & 0x1)
#define SCODE_SEVERITY(sc) (((sc) >> 31) & 0x1)
#define MAKE_HRESULT(sev, fac, code) \
    ((HRESULT)(((unsigned long)(sev) << 31) | ((unsigned long)(fac) << 16) | ((unsigned long)(code))))
#define MAKE_SCODE(sev, fac, code) \
    ((SCODE)(((unsigned long)(sev) << 31) | ((unsigned long)(fac) << 16) | ((unsigned long)(code))))

#define FACILITY_NT_BIT 0x10000000
#define __HRESULT_FROM_WIN32(x) \
    ((HRESULT)(x) <= 0 ? ((HRESULT)(x)) : ((HRESULT)(((x) & 0x0000FFFF) | (FACILITY_WIN32 << 16) | 0x80000000)))

#ifndef _HRESULT_DEFINED
#define _HRESULT_DEFINED
typedef long HRESULT;
#endif

// Win32 error code -> HRESULT: non-positive values pass through; others get FACILITY_WIN32 and the failure bit.
// (An inline function, not a macro: the argument is evaluated once and converted to long.)
__forceinline HRESULT HRESULT_FROM_WIN32(long x)
{
    if (x <= 0)
        return (HRESULT)x;
    return (HRESULT)((x & 0x0000FFFF) | (FACILITY_WIN32 << 16) | 0x80000000);
}

#define HRESULT_FROM_NT(x) ((HRESULT)((x) | FACILITY_NT_BIT))
