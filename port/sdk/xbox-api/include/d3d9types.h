// A D3DDECLTYPE packs GPUVERTEXFORMAT (bits 0-5), GPUENDIAN (6-7), GPUVERTEXSIGN (8), GPUNUMFORMAT (9) and four
// GPUSWIZZLE selectors (3 bits each from bit 10).
#define D3DDECLTYPE_VERTEXFORMAT_SHIFT              0
#define D3DDECLTYPE_ENDIAN_SHIFT                    6
#define D3DDECLTYPE_VERTEXSIGN_SHIFT                8
#define D3DDECLTYPE_NUMFORMAT_SHIFT                 9
#define D3DDECLTYPE_SWIZZLEX_SHIFT                  10
#define D3DDECLTYPE_SWIZZLEY_SHIFT                  13
#define D3DDECLTYPE_SWIZZLEZ_SHIFT                  16
#define D3DDECLTYPE_SWIZZLEW_SHIFT                  19

#define MAKED3DDECLTYPE(VertexFormat, Endian, VertexSign, NumFormat, Swizzle) \
    ((VertexFormat) << D3DDECLTYPE_VERTEXFORMAT_SHIFT | (Endian) << D3DDECLTYPE_ENDIAN_SHIFT | \
     (VertexSign) << D3DDECLTYPE_VERTEXSIGN_SHIFT | (NumFormat) << D3DDECLTYPE_NUMFORMAT_SHIFT | \
     (Swizzle) << D3DDECLTYPE_SWIZZLEX_SHIFT)

#define MAKED3DDECLTYPE2(VertexFormat, Endian, VertexSign, NumFormat, SwizzleX, SwizzleY, SwizzleZ, SwizzleW) \
    ((VertexFormat) << D3DDECLTYPE_VERTEXFORMAT_SHIFT | (Endian) << D3DDECLTYPE_ENDIAN_SHIFT | \
     (VertexSign) << D3DDECLTYPE_VERTEXSIGN_SHIFT | (NumFormat) << D3DDECLTYPE_NUMFORMAT_SHIFT | \
     (SwizzleX) << D3DDECLTYPE_SWIZZLEX_SHIFT | (SwizzleY) << D3DDECLTYPE_SWIZZLEY_SHIFT | \
     (SwizzleZ) << D3DDECLTYPE_SWIZZLEZ_SHIFT | (SwizzleW) << D3DDECLTYPE_SWIZZLEW_SHIFT)

