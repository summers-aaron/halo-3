// ---- Register tags (unbuffered "Gpu" APIs and D3DTAGCOLLECTION) -----------------------------------------------

// A tag is (mask word << 16) | (bit count << 8) | first bit; bit 0 is the most significant bit of the word.
#define D3DTAG_INDEX(Tag)                           ((DWORD) ((Tag) >> 16))
#define D3DTAG_COUNT(Tag)                           ((DWORD) ((Tag) >> 8) & 0xff)
#define D3DTAG_START(Tag)                           ((DWORD) ((Tag) & 0xff))

// Mask of bits StartBit..EndBit (inclusive), counted from the MSB: an arithmetic shift smears the top bit.
#define D3DTAG_MASKENCODE(StartBit, EndBit) \
    ((UINT64) ((INT64) 0x8000000000000000ULL >> ((EndBit) - (StartBit))) >> (StartBit))

