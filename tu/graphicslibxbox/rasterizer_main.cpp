// @address 0x4542e0 rasterizer_main_evaluate_curve
float rasterizer_main_evaluate_curve(const real_point2d *points, float x)
{
    long index = 1;
    if (x < 0.0f) {
        x = 0.0f;
    }
    while (points[index].x < x) {
        index++;
    }
    const real_point2d *current = &points[index];
    const real_point2d *previous = current - 1;
    return (x - previous->x) / (current->x - previous->x) * (current->y - previous->y) + previous->y;
}

