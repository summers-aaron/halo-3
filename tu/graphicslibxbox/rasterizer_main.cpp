// @address 0x450768 rasterizer_main_decompress_texture
void rasterizer_main_decompress_texture(unsigned char *output, const rasterizer_main_texture_definition *definition)
{
    unsigned int count_mask = (1 << definition->format) - 1;
    unsigned int value_mask = (1 << (8 - definition->format)) - 1;
    long data_size = definition->data_size;
    long x = 0;
    long y = 0;
    for (long index = 0; index < data_size; index++) {
        unsigned char packed = ((const unsigned char *)definition->data)[index];
        unsigned char value = (packed & value_mask) << definition->format;
        unsigned char count = ((packed >> (unsigned char)(8 - definition->format)) & count_mask) + 1;
        // match: 0x450768: byte loop index pins saved-reg allocation (long spills to savegprlr_29 with r28-r29 recolor)
        for (unsigned char run_index = 0; run_index < count; run_index++) {
            unsigned int target_x = definition->offset_low + x;
            unsigned int target_y = definition->offset_high + y;
            if (target_x <= 255 && target_y <= 121)
                output[(target_y << 8) + target_x] = value;
            x++;
        }
        if (x == definition->width) {
            x = 0;
            y++;
        }
    }
}


