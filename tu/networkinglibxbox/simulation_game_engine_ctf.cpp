bool c_simulation_ctf_engine_globals_definition::entity_update_decode(
    bool initial_update,
    unsigned long *update_mask,
    long state_data_size,
    void *state_data,
    c_bitstream *packet,
    bool use_encoding)
{
    s_ctf_engine_state_data *state = (s_ctf_engine_state_data *)state_data;
    unsigned long decoded_mask = 0;
    bool success = true;
    success = success && c_simulation_game_engine_globals_definition::global_update_decode(
        &decoded_mask,
        (s_game_engine_state_data *)state,
        packet);
    unsigned long mask;

    if (packet->read_bool("defensive-team-exists"))
    {
        long defensive_team = packet->read_integer("defensive-team", 4) - 1;
        state->defensive_team = defensive_team;
        if (defensive_team != -1)
        {
            success = (success && defensive_team >= 0) ? (defensive_team < 8) : 0;
        }
        mask = decoded_mask | 0x40;
    }
    else
    {
        mask = decoded_mask;
    }

    if (packet->read_bool("flag-swap-timer"))
    {
        long flag_swap_timer = packet->read_integer("flag-swap-timer", 16);
        state->flag_swap_timer = flag_swap_timer;
        success = success && flag_swap_timer >= 0;
        mask |= 0x80;
    }

    if (packet->read_bool("touch-return-timers"))
    {
        for (long timer_index = 0; timer_index < 9; ++timer_index)
        {
            if (packet->read_bool("touch-return-timer-exists"))
            {
                state->touch_return_timers[timer_index] = packet->read_integer("touch-return-timer", 16);
            }
            else
            {
                state->touch_return_timers[timer_index] = -1;
            }
        }
        mask |= 0x100;
    }

    if (packet->read_bool("flag-reset-timers"))
    {
        for (long timer_index = 0; timer_index < 9; ++timer_index)
        {
            if (packet->read_bool("flag-reset-timer-exists"))
            {
                state->flag_reset_timers[timer_index] = (short)packet->read_integer("flag-reset-timer", 8);
            }
            else
            {
                state->flag_reset_timers[timer_index] = -1;
            }
        }
        mask |= 0x200;
    }

    if (packet->read_bool("flag-weapon-flags"))
    {
        for (long flag_index = 0; flag_index < 9; ++flag_index)
        {
            if (packet->read_bool("flag-weapon-flag-exists"))
            {
                state->flag_weapon_flags[flag_index] = (unsigned char)packet->read_integer("flag-weapon-flag", 2);
            }
            else
            {
                state->flag_weapon_flags[flag_index] = 0;
            }
        }
        mask |= 0x400;
    }

    if (packet->read_bool("helper-flags-exist"))
    {
        state->helper_flags = (unsigned short)packet->read_integer("helper-flags", 3);
        mask |= 0x800;
    }

    success = success && mask != 0;
    *update_mask = mask;
    return success;
}

