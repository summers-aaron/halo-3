// 0x3f7ae0
void c_network_session_parameters::check_to_send_updates()
{
    const c_network_session_membership *membership = m_session->get_session_membership();
    long local_peer_index = membership->local_peer_index();
    for (long peer_index = membership->get_first_peer(); peer_index != -1; peer_index = membership->get_next_peer(peer_index))
    {
        if (peer_index == local_peer_index)
            continue;
        bool connected = membership->get_peer(peer_index)->connection_state >= 4;
        if (!connected)
            continue;
        if (membership->get_peer_needs_reestablishment(peer_index))
            continue;
        s_network_message_parameters_update message;
        message.session_id.key_identifier[0] = 0;
        for (long i = 1; i < k_transport_secure_identifier_length; i++)
            message.session_id.key_identifier[i] = 0;
        memset(&message.initial_update, 0, sizeof(message) - 8);
        unsigned __int64 update_mask = 0;
        long update_size = 0;
        add_parameters_to_update(peer_index, membership->get_peer(peer_index)->connection_state != 8, message.payload,
            sizeof(message.payload), &update_mask, &update_size);
        if (update_mask == 0)
            continue;
        c_network_session *m_session = this->m_session;
        long channel_index = -1;
        channel_index = m_session->get_peer_observer_channel(peer_index);
        if (!m_observer->observer_channel_connected(m_session->observer_owner(), channel_index))
            continue;
        if (m_observer->observer_channel_backlogged(m_session->observer_owner(), channel_index, _network_message_type_parameters_update))
        {
            m_observer->observer_channel_set_waiting_on_backlog(m_session->observer_owner(), channel_index, _network_message_type_parameters_update);
        }
        else
        {
            m_session->get_session_id((s_transport_secure_identifier *)&message.session_id);
            long peer_bit = 1 << peer_index;
            message.updated_parameters = update_mask;
            message.initial_update = (peer_bit & m_peers_reset_mask) == 0;
            for (long parameter_index = 0; parameter_index < 47; parameter_index++)
            {
                if (!m_parameter_interfaces[parameter_index]->get_allowed())
                    message.cleared_parameters |= 1i64 << parameter_index;
            }
            m_observer->observer_channel_send_message(m_session->observer_owner(), channel_index, false,
                _network_message_type_parameters_update, sizeof(message), &message);
            m_peers_reset_mask |= peer_bit;
            for (long parameter_index = 0; parameter_index < 47; parameter_index++)
            {
                if ((update_mask & (1i64 << parameter_index)) != 0)
                {
                    c_network_session_parameter_base *parameter = m_parameter_interfaces[parameter_index];
                    parameter->notify_update_sent_to_peer(peer_index);
                }
            }
        }
    }
}


