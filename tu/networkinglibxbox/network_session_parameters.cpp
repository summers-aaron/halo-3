void c_network_session_parameters::check_to_send_change_requests()
{
    long host_peer_index = m_session->get_session_membership()->host_peer_index();
    if (host_peer_index == -1)
        return;
    long channel_index = m_session->get_peer_observer_channel(host_peer_index);
    if (channel_index == -1)
        return;
    s_network_message_parameters_request request;
    unsigned char *data = request.data;
    unsigned long total_size = 0;
    memset(&request, 0, sizeof(request));
    m_session->get_session_id(&request.session_id);
    for (long parameter_index = 0; parameter_index < sizeof(m_parameter_interfaces) / sizeof(m_parameter_interfaces[0]); parameter_index++)
    {
        c_network_session_parameter_base *parameter = m_parameter_interfaces[parameter_index];
        if (parameter->desires_change_request())
        {
            long size = parameter->get_change_request_size();
            if (total_size + size > sizeof(request.data))
                break;
            parameter->build_change_request(host_peer_index, data, size);
            request.parameter_flags |= 1i64 << parameter_index;
            data += size;
            total_size += size;
        }
    }
    if (request.parameter_flags == 0)
        return;
    if (!m_observer->observer_channel_connected(m_session->observer_owner(), channel_index))
        return;
    if (m_observer->observer_channel_backlogged(m_session->observer_owner(), channel_index, _network_message_type_parameters_request))
    {
        m_observer->observer_channel_set_waiting_on_backlog(m_session->observer_owner(), channel_index, _network_message_type_parameters_request);
    }
    else
    {
        m_observer->observer_channel_send_message(m_session->observer_owner(), channel_index, false,
            _network_message_type_parameters_request, sizeof(request), &request);
        for (long parameter_index = 0; parameter_index < sizeof(m_parameter_interfaces) / sizeof(m_parameter_interfaces[0]); parameter_index++)
        {
            if (request.parameter_flags & (1i64 << parameter_index))
                m_parameter_interfaces[parameter_index]->notify_change_request_sent();
        }
    }
}

