// 0x3fb5e8
template<> bool c_network_session_parameter_chunked<s_network_session_parameter_saved_film_game_options>::handle_update_payload(const void *payload)
{
    const s_network_session_parameter_chunked_change_request *update = (const s_network_session_parameter_chunked_change_request *)payload;
    bool success = false;
    bool valid = false;

    if (update->chunk_index == 0)
    {
        if (update->chunk_count > 0 && update->chunk_count <= m_maximum_chunk_count &&
            update->transmit_size > 0 && (unsigned long)update->transmit_size <= sizeof(m_update_data))
        {
            m_update_chunk_count = update->chunk_count;
            m_update_size = update->transmit_size;
            m_update_checksum = update->transmit_checksum;
            valid = true;
        }
    }
    else if (update->chunk_index >= 0 && update->chunk_index < m_update_chunk_count &&
             update->chunk_index == m_received_update_chunk_index + 1)
    {
        valid = true;
    }

    if (valid)
    {
        long chunk_size = 0;
        char *chunk_destination = network_session_parameters_get_chunk_offset_by_chunk_index(
            m_update_data, sizeof(m_update_data), m_update_size, update->chunk_index,
            m_update_chunk_count, k_network_session_parameter_chunk_size, &chunk_size);

        memcpy(chunk_destination, update->chunk_data, chunk_size);
        m_received_update_chunk_index = update->chunk_index;
        success = true;

        if (update->chunk_index == m_update_chunk_count - 1)
        {
            unsigned long checksum = network_session_parameters_crc_new();
            checksum = crc_checksum_buffer(checksum, m_update_data, m_update_size);
            if (checksum != m_update_checksum)
            {
                success = false;
            }
            else
            {
                c_bitstream packet;
                bitstream_initialize(&packet, (const unsigned char *)m_update_data, m_update_size);
                s_network_session_parameter_saved_film_game_options decoded_data;
                memset(&decoded_data, 0, sizeof(decoded_data));
                packet.begin_reading();
                success = decode_update(&packet, &decoded_data);
                if (success)
                    m_data = decoded_data;
            }
        }
    }

    if (!success)
    {
        m_update_checksum = 0xffffffff;
        m_update_chunk_count = -1;
        m_update_size = -1;
        m_received_update_chunk_index = -1;
    }

    return success;
}

