// @address 0x39aa40 ?_tr_align@@YAXPAUdeflate_state_s@@@Z
void _tr_align(deflate_state *s)
{
    send_bits(s, STATIC_TREES << 1, 3);
    send_code(s, END_BLOCK, trees_static_ltree);
    D3DX::bi_flush((D3DX::internal_state *)s);
    /* Of the 10 bits for the empty block, we have already sent
     * (10 - bi_valid) bits. The lookahead for the last real code (before
     * the EOB of the previous block) was thus at least one plus the length
     * of the EOB plus what we have just sent of the empty static block.
     */
    if (1 + s->last_eob_len + 10 - s->bi_valid < 9) {
        send_bits(s, STATIC_TREES << 1, 3);
        send_code(s, END_BLOCK, trees_static_ltree);
        D3DX::bi_flush((D3DX::internal_state *)s);
    }
    s->last_eob_len = 7;
}

// @address 0x39b3b0 ?bi_flush@D3DX@@YAXPAUinternal_state@1@@Z
void D3DX::bi_flush(D3DX::internal_state *s)
{
    if (s->bi_valid == 16) {
        put_short(s, s->bi_buf);
        s->bi_buf = 0;
        s->bi_valid = 0;
    } else if (s->bi_valid >= 8) {
        put_byte(s, (Byte)s->bi_buf);
        s->bi_buf >>= 8;
        s->bi_valid -= 8;
    }
}

// @address 0x39b440 ?bi_windup@D3DX@@YAXPAUinternal_state@1@@Z
void D3DX::bi_windup(D3DX::internal_state *s)
{
    if (s->bi_valid > 8) {
        put_short(s, s->bi_buf);
    } else if (s->bi_valid > 0) {
        put_byte(s, (Byte)s->bi_buf);
    }
    s->bi_buf = 0;
    s->bi_valid = 0;
}
