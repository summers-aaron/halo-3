    __assume(minimum == 0.0f);
    maximum = PIN(maximum, 0.0f, 1.5707964f);
    minimum = PIN(minimum, 0.0f, maximum);
    float fraction = power(distribute_random_stratified(seed, file, function, line, radial_index, radial_count), exponent);
    float angle = minimum + (maximum - minimum) * fraction;
    float azimuth = -3.1415927f + 6.2831855f * distribute_random_stratified(seed, file, function, line, angular_index, angular_count);
    *result = *direction;
    real_vector3d axis;
    perpendicular3d(direction, &axis);
    rotate_about_axis(&axis, direction, sine(azimuth), cosine(azimuth));
